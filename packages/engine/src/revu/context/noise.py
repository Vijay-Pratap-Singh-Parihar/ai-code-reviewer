"""Files a reviewer shouldn't spend tokens on: lockfiles, minified bundles,
vendored dependencies and code a tool generated.

People don't review these line by line either, and they are often the
largest part of a diff (a dependency bump rewrites thousands of lockfile
lines). Sending them costs money, pushes the real change out of a small
model's context, and invites comments nobody will act on. Dropping a whole
file never shifts the line numbers of the files that stay.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import PurePosixPath

from revu.context.diff import block_path, parse_diff, split_file_blocks

LOCKFILES = frozenset(
    {
        "package-lock.json",
        "npm-shrinkwrap.json",
        "yarn.lock",
        "pnpm-lock.yaml",
        "bun.lockb",
        "poetry.lock",
        "uv.lock",
        "Pipfile.lock",
        "pdm.lock",
        "Cargo.lock",
        "Gemfile.lock",
        "composer.lock",
        "go.sum",
        "mix.lock",
        "pubspec.lock",
        "Podfile.lock",
        "packages.lock.json",
        "gradle.lockfile",
        "flake.lock",
    }
)

GENERATED_SUFFIXES = (
    ".min.js",
    ".min.css",
    ".js.map",
    ".css.map",
    ".pb.go",
    ".pb.cc",
    ".pb.h",
    "_pb2.py",
    "_pb2.pyi",
    "_pb2_grpc.py",
    ".g.dart",
    ".freezed.dart",
    ".snap",
)

VENDORED_DIRS = frozenset({"node_modules", "vendor", "__snapshots__"})

# The conventional "don't edit me" headers: Go's, Facebook's @generated,
# .NET's <auto-generated>, and the common prose form.
_GENERATED_MARKER = re.compile(
    r"@generated\b|Code generated .* DO NOT EDIT|<auto-generated|"
    r"This file (?:is|was|has been) (?:automatically |auto-?)?generated",
    re.IGNORECASE,
)
_MARKER_LINES = 10


def skip_reason(path: str, block: str = "") -> str | None:
    """Why `path` isn't worth reviewing, or `None` if it is. `block` is the
    file's diff, checked for a generated-code header near the top."""
    p = PurePosixPath(path)
    if p.name in LOCKFILES:
        return "lockfile"
    if p.name.endswith(GENERATED_SUFFIXES):
        return "generated"
    if VENDORED_DIRS.intersection(p.parts[:-1]):
        return "vendored"
    if block and _has_generated_header(block):
        return "generated"
    return None


def _has_generated_header(block: str) -> bool:
    for file_diff in parse_diff(block):
        for hunk in file_diff.hunks:
            for line in hunk.lines:
                near_top = line.new_lineno is not None and line.new_lineno <= _MARKER_LINES
                if near_top and _GENERATED_MARKER.search(line.content):
                    return True
    return False


@dataclass(frozen=True)
class FilteredDiff:
    diff: str
    skipped: list[str] = field(default_factory=list)


def drop_noise(diff_text: str) -> FilteredDiff:
    """The diff without the files `skip_reason` rejects, and their paths."""
    kept: list[str] = []
    skipped: list[str] = []
    for block in split_file_blocks(diff_text):
        path = block_path(block)
        if path and skip_reason(path, block):
            skipped.append(path)
        else:
            kept.append(block)
    return FilteredDiff("".join(kept), skipped)
